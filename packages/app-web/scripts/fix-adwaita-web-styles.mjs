// Temporary workaround for the @gjsify/adwaita-web@0.15.1 publish regression.
//
// adwaita-web's root entry (`src/index.ts`) does
// `import { ADWAITA_WEB_CSS } from './styles.generated.js'` to self-inject its
// compiled skin on import. That file is a `build:scss` artifact listed under
// `.gitignore`, and `gjsify pack` honours `.gitignore` even for paths in the
// `files` allowlist — so the 0.15.1 tarball ships `src/index.ts` WITHOUT
// `src/styles.generated.ts`. A bundler (Vite dev or `gjsify build --app
// browser`) then fails to resolve `./styles.generated.js`.
//
// The compiled CSS itself IS shipped (`dist/adwaita-web.css`), so we regenerate
// the missing module from it. Idempotent + no-op once the file exists.
//
// REMOVE this script (and its two call sites in package.json) once adwaita-web
// republishes with `styles.generated` present (> 0.15.1). Root cause + fix to
// track upstream: adwaita-web should either commit the generated file (like
// @gjsify/tsc commits its lib*.d.ts) or `gjsify pack` should not drop a
// `files`-allowlisted path just because it is gitignored.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);

// `dist/adwaita-web.css` is exposed via the package's exports map
// (`@gjsify/adwaita-web/style.css`), so it resolves even under the exports
// restriction that hides `./package.json`.
const cssPath = require.resolve('@gjsify/adwaita-web/style.css');
const pkgDir = dirname(dirname(cssPath)); // .../adwaita-web
const target = join(pkgDir, 'src', 'styles.generated.ts');

if (existsSync(target)) {
    process.exit(0);
}

const css = readFileSync(cssPath, 'utf8');
writeFileSync(target, `// Regenerated by app-web/scripts/fix-adwaita-web-styles.mjs (0.15.1 workaround).\nexport const ADWAITA_WEB_CSS = ${JSON.stringify(css)};\n`);
console.log('[app-web] regenerated @gjsify/adwaita-web src/styles.generated.ts (0.15.1 publish workaround)');
